"""themes/syncline/pictograms.json → dist/syncline/pictograms/<name>[-active].svg + pictograms.sprite.svg + pictograms.js

Colours are emitted as `var(--form-<energy>, #fallback)` so inline SVG follows tokens.css; the
fallback is the theme's energy base so the file still renders as a standalone image.

usage: python3 -I build/pictograms.py
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
P = json.load(open(ROOT / "themes" / "syncline" / "pictograms.json"))
T = json.load(open(ROOT / "themes" / "syncline" / "theme.json"))

def form_colour(form):
    return T["energy"][form]["light"]["base"]["$value"]

g = P["grid"]
out = ROOT / "dist" / "syncline" / "pictograms"
out.mkdir(parents=True, exist_ok=True)

def shape_markup(s, slots):
    form = slots[s["slot"]]
    col = f'var(--form-{form}, {form_colour(form)})'
    extra = ""
    if "opacity" in s:
        extra += f' opacity="{s["opacity"]}"'
    if s["type"] == "path":
        return f'<path d="{s["d"]}" fill="none" stroke="{col}" stroke-width="{g["stroke"]}" stroke-linecap="round" stroke-linejoin="round"{extra}/>'
    if s["type"] == "circle":
        return f'<circle cx="{s["cx"]}" cy="{s["cy"]}" r="{s["r"]}" fill="{col}"{extra}/>'
    if s["type"] == "rect":
        return f'<rect x="{s["x"]}" y="{s["y"]}" width="{s["w"]}" height="{s["h"]}" rx="{s["rx"]}" fill="{col}"{extra}/>'
    raise ValueError(s["type"])

symbols, js = [], {}
for name, pic in P["pictograms"].items():
    for state, slots in P["slots"].items():
        body = "".join(shape_markup(s, slots) for s in pic["shapes"])
        suffix = "" if state == "idle" else "-active"
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {g["size"]} {g["size"]}" fill="none" '
               f'aria-hidden="true" focusable="false" class="syncline-pictogram" data-pictogram="{name}" data-state="{state}">{body}</svg>')
        (out / f"{name}{suffix}.svg").write_text(svg, encoding="utf-8")
        symbols.append(f'<symbol id="picto-{name}{suffix}" viewBox="0 0 {g["size"]} {g["size"]}">{body}</symbol>')
        js[f"{name}{suffix}"] = svg

(out / "pictograms.sprite.svg").write_text(
    '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">' + "".join(symbols) + "</svg>", encoding="utf-8")
(out / "pictograms.js").write_text(
    "// generated by build/pictograms.py — do not edit\nexport const pictograms = " + json.dumps(js, indent=2) + ";\n", encoding="utf-8")
print(f"wrote {len(js)} pictograms → {out}")
