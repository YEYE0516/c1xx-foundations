"""UI icon system.

1. vendor  : copy the glyphs named in foundations/icons.json from a lucide-static checkout into
             foundations/icons/<name>.svg, normalised (24 grid, currentColor, stroke 2, no ids/classes)
2. build   : foundations/icons/*.svg → dist/icons/{sprite.svg, icons.json, icons.css, manifest.md}

usage: python3 -I build/icons.py vendor <path/to/lucide-static/icons>
       python3 -I build/icons.py build
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
M = json.load(open(ROOT / "foundations" / "icons.json"))
SRC = ROOT / "foundations" / "icons"
OUT = ROOT / "dist" / "icons"
NAMES = [n for c in M["categories"].values() for n in c["icons"]]
assert len(NAMES) == len(set(NAMES)), "duplicate icon name"
for n in NAMES:
    assert re.fullmatch(M["naming"]["pattern"], n), n

def body_of(svg_text):
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg_text, re.S).group(1)
    inner = re.sub(r"<!--.*?-->", "", inner, flags=re.S)
    return re.sub(r"\s+", " ", inner).strip()

def normalised(name, body):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
            f'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
            f'data-icon="{name}" aria-hidden="true">{body}</svg>\n')

def vendor(src):
    src = pathlib.Path(src)
    SRC.mkdir(parents=True, exist_ok=True)
    for n in NAMES:
        f = src / f"{n}.svg"
        if not f.exists():
            sys.exit(f"missing in lucide: {n}")
        (SRC / f"{n}.svg").write_text(normalised(n, body_of(f.read_text())), encoding="utf-8")
    (SRC / "LICENSE").write_text(
        "Glyphs in this folder are from Lucide (https://lucide.dev), ISC License.\n"
        "Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of Feather (MIT).\n"
        "All other copyright (c) for Lucide are held by Lucide Contributors 2022.\n"
        "Normalised for C1XX Foundations: 24 grid, currentColor, stroke 2, data-icon attribute.\n", encoding="utf-8")
    print(f"vendored {len(NAMES)} icons → {SRC}")

def build():
    OUT.mkdir(parents=True, exist_ok=True)
    symbols, index = [], {}
    for cat, c in M["categories"].items():
        for n in c["icons"]:
            body = body_of((SRC / f"{n}.svg").read_text())
            symbols.append(f'<symbol id="icon-{n}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{body}</symbol>')
            index[n] = {"category": cat, "body": body}
    (OUT / "sprite.svg").write_text('<svg xmlns="http://www.w3.org/2000/svg" style="display:none">' + "".join(symbols) + "</svg>\n", encoding="utf-8")
    (OUT / "icons.json").write_text(json.dumps({"grid": M["grid"], "sizes": {k: v for k, v in M["sizes"].items() if not k.startswith("$")}, "icons": index}, indent=1), encoding="utf-8")
    css = [
        "/* C1XX Foundations · icons — generated by build/icons.py */",
        ".icon { display: inline-block; width: var(--size-icon-md); height: var(--size-icon-md); flex: none; color: inherit; vertical-align: middle; }",
        ".icon--sm { width: var(--size-icon-sm); height: var(--size-icon-sm); }",
        ".icon--lg { width: var(--size-icon-lg); height: var(--size-icon-lg); }",
        ".icon--secondary { color: var(--fg-secondary); } .icon--muted { color: var(--fg-muted); } .icon--accent { color: var(--fg-accent); }",
        ".icon--signal { color: var(--action-signal); } .icon--disabled { color: var(--action-disabled-fg); }",
        ".icon-button { display: inline-grid; place-items: center; width: var(--size-control-md); height: var(--size-control-md); border-radius: var(--radius-full); position: relative; }",
        ".icon-button--lg { width: var(--size-control-lg); height: var(--size-control-lg); }",
        ".icon-button::after { content: ''; position: absolute; inset: calc((var(--size-control-md) - var(--size-touch-min)) / 2); }",
        "",
    ]
    (OUT / "icons.css").write_text("\n".join(css), encoding="utf-8")
    md = ["# Icon manifest", "", f"{len(NAMES)} icons · 24 grid · stroke 2 · sizes 16 / 20 / 24", ""]
    for cat, c in M["categories"].items():
        md.append(f"## {cat} — {c['$description']}")
        md.append("")
        md.append(" · ".join(f"`{n}`" for n in c["icons"]))
        md.append("")
    (OUT / "manifest.md").write_text("\n".join(md), encoding="utf-8")
    print(f"built {len(NAMES)} icons → {OUT}")

if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "build"
    if cmd == "vendor":
        vendor(sys.argv[2])
    build()
